const LANG_KEY = 'quizzup-lang';
const missingTranslations = new Set();

function detectDefaultLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'fr' || saved === 'en' || saved === 'es') return saved;
  } catch { /* localStorage unavailable */ }
  const nav = (navigator.language || '').toLowerCase();
  if (nav.startsWith('fr')) return 'fr';
  if (nav.startsWith('es')) return 'es';
  return 'en';
}

function interpolate(template, vars) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => (key in vars ? String(vars[key]) : `{${key}}`));
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(detectDefaultLang);

  const setLang = useCallback((next) => {
    setLangState(next);
    try { localStorage.setItem(LANG_KEY, next); } catch { /* ignore */ }
  }, []);

  const toggleLang = useCallback(() => {
    const order = ['fr', 'en', 'es'];
    const next = order[(order.indexOf(lang) + 1) % order.length];
    setLang(next);
  }, [lang, setLang]);

  const t = useCallback((key, vars) => {
    const pluralKey = Number(vars?.n) === 1 && STRINGS[lang][`${key}One`] ? `${key}One` : key;
    const template = STRINGS[lang][pluralKey] ?? STRINGS.fr[pluralKey];
    if (template === undefined) {
      if (!missingTranslations.has(key)) {
        missingTranslations.add(key);
        console.error(`[QuizzUp i18n] Missing translation: ${key}`);
      }
      return '…';
    }
    return interpolate(template, vars);
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, toggleLang, t }), [lang, setLang, toggleLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

// Reusable catalogue cards also render outside the application provider in
// static previews. Inside the app they follow the same live language state.
export function useOptionalI18n() {
  return useContext(I18nContext);
}
